static void gterm_scroll() {
    for (int r = 0; r < TERM_HEIGHT - 1; r++) {
        for (int c = 0; c < TERM_WIDTH; c++) {
            text_buffer[r][c] = text_buffer[r + 1][c];
        }
    }
    for (int c = 0; c < TERM_WIDTH; c++) {
        text_buffer[TERM_HEIGHT - 1][c] = ' ';
    }
    
    for (int r = 0; r < TERM_HEIGHT; r++) {
        for (int c = 0; c < TERM_WIDTH; c++) {
            gterm_draw_char(c, r, text_buffer[r][c], fg_color, bg_color);
        }
    }
	video_swap_buffers();
}

void gterm_putchar(char c) {
    if (c == '\0') return;

    if (c == '\n') {
        cursor_x = 0;
        cursor_y++;
    } else if (c == '\r') {
        cursor_x = 0;
    } else if (c == '\b') {
        if (cursor_x > 0) {
            cursor_x--;
            text_buffer[cursor_y][cursor_x] = ' ';
            gterm_draw_char(cursor_x, cursor_y, ' ', fg_color, bg_color);
        }
    } else {
        if ((unsigned char)c >= 32) {
            text_buffer[cursor_y][cursor_x] = c;
            gterm_draw_char(cursor_x, cursor_y, c, fg_color, bg_color);
            cursor_x++;
        }
    }

    if (cursor_x >= TERM_WIDTH) {
        cursor_x = 0;
        cursor_y++;
    }

    if (cursor_y >= TERM_HEIGHT) {
        gterm_scroll();
        cursor_y = TERM_HEIGHT - 1;
    }
    
    // --- ADAUGĂ ACEASTĂ LINIE OBLIGATORIU ---
    //video_swap_buffers();
}

void gterm_print(const char* str) {
    while (*str) {
        gterm_putchar(*str++);
    }
}

void gterm_draw_cursor_box(int x, int y, uint32_t color) {
    // Sablon simplu de săgeată de mouse (8x12 pixeli)
    static const uint8_t cursor_shape[12] = {
        0b10000000,
        0b11000000,
        0b11100000,
        0b11110000,
        0b11111000,
        0b11111100,
        0b11111110,
        0b11110000,
        0b10111000,
        0b00011100,
        0b00001110,
        0b00000110
    };

    for (int row = 0; row < 12; row++) {
        for (int col = 0; col < 8; col++) {
            if (cursor_shape[row] & (1 << (7 - col))) {
                // `put_pixel` verifică singur limitele ecranului și folosește back_buffer!
                put_pixel(x + col, y + row, color);
            }
        }
    }
}