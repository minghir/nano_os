void gterm_draw_char(int col, int row, unsigned char c, uint32_t fg, uint32_t bg) {
    VideoModeInfo* mode = video_get_info();
    if (!mode || !mode->back_buffer) return;

    int start_x = col * 8;
    int start_y = row * 16;

    // Verificare limite ecran (opțional, dar bun pentru siguranță)
    if (start_x < 0 || start_x + 8 > (int)mode->width || 
        start_y < 0 || start_y + 16 > (int)mode->height) {
        return;
    }

    const unsigned char* glyph = font8x16[c];
    
    // Verificare glifă goală
    int empty = 1;
    for (int i = 0; i < 16; i++) {
        if (glyph[i] != 0) {
            empty = 0;
            break;
        }
    }
    if (empty && c != ' ') {
        glyph = fallback_glyph;
    }

    uint32_t pitch_pixels = mode->pitch / 4; // Câți pixeli sunt pe o linie fizică

    // Desenăm linie cu linie (16 rânduri)
    for (int y = 0; y < 16; y++) {
        unsigned char line = glyph[y];
        
        // Calculăm adresa de start în back_buffer pentru linia curentă
        uint32_t* dest = &mode->back_buffer[((start_y + y) * pitch_pixels) + start_x];

        // Desenăm cei 8 pixeli ai liniei dintr-o singură mișcare, fără put_pixel
        dest[0] = (line & 0x80) ? fg : bg;
        dest[1] = (line & 0x40) ? fg : bg;
        dest[2] = (line & 0x20) ? fg : bg;
        dest[3] = (line & 0x10) ? fg : bg;
        dest[4] = (line & 0x08) ? fg : bg;
        dest[5] = (line & 0x04) ? fg : bg;
        dest[6] = (line & 0x02) ? fg : bg;
        dest[7] = (line & 0x01) ? fg : bg;
    }
}

