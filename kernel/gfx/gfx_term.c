void gterm_clear() {
    VideoModeInfo* mode = video_get_info();
    if (!mode->back_buffer) return;

    // Umplem back buffer-ul cu culoarea de fundal
    for (uint32_t y = 0; y < mode->height; y++) {
        for (uint32_t x = 0; x < mode->width; x++) {
            uint32_t index = (y * (mode->pitch / 4)) + x;
            mode->back_buffer[index] = bg_color;
        }
    }
    cursor_x = 0;
    cursor_y = 0;
    
    for (int r = 0; r < TERM_HEIGHT; r++) {
        for (int c = 0; c < TERM_WIDTH; c++) {
            text_buffer[r][c] = ' ';
        }
    }
    
    // După ce am curățat bufferul, facem swap instant pe ecran
    video_swap_buffers();
}

